"""Refresh the repository-only API snapshot directly from public Python objects."""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def prepare() -> None:
    """Generate the legacy API snapshot without maintaining signatures by hand.

    Notes
    -----
    Existing scientific regression tests and GitHub readers use docs/api.md.
    It is excluded from the website, whose API is rendered by mkdocstrings.
    The snapshot is generated from exactly the same source on every site build.
    """
    sys.path.insert(0, str(ROOT / "src"))
    import curvefit_stats

    sections = [
        "# API reference (generated repository snapshot)",
        "<!-- Generated by docs/_tools/prepare.py. "
        "Do not edit signatures or docstrings. -->",
        "This repository-only snapshot preserves the existing regression and offline "
        "reading contract. The website renders the source directly with mkdocstrings; "
        "this snapshot is excluded from its navigation and search. "
        "See [the API website](https://bibymaths.github.io/curvefit-stats/reference/).",
    ]
    for name in curvefit_stats.__all__:
        obj = getattr(curvefit_stats, name)
        sections.extend(
            [
                f"## {name}",
                f"```text\n{name}{inspect.signature(obj)}\n```",
                f"```text\n{inspect.getdoc(obj)}\n```",
            ]
        )
        if name == "GlobalFitGroup":
            sections.extend(
                [
                    "### GlobalFitGroup.fit",
                    f"```text\nfit{inspect.signature(obj.fit)}\n```",
                    f"```text\n{inspect.getdoc(obj.fit)}\n```",
                ]
            )
    target = ROOT / "docs/api.md"
    content = "\n\n".join(sections) + "\n"
    if target.read_text() != content:
        target.write_text(content)


if __name__ == "__main__":
    prepare()
